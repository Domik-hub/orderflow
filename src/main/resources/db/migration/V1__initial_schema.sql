CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    display_name VARCHAR(80) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('USER', 'ADMIN'))
);
CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    price NUMERIC(12,2) NOT NULL CHECK (price BETWEEN 0.01 AND 9999999.99),
    stock BIGINT NOT NULL CHECK (stock >= 0),
    active BOOLEAN NOT NULL
);
CREATE INDEX idx_products_active_price_id ON products(active, price, id);
CREATE TABLE cart_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    product_id BIGINT NOT NULL REFERENCES products(id),
    quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 99),
    CONSTRAINT uq_cart_user_product UNIQUE(user_id, product_id)
);
CREATE TABLE shop_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    idempotency_key VARCHAR(36) NOT NULL,
    shipping_address VARCHAR(300) NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('PLACED','SHIPPED','CANCELLED')),
    total NUMERIC(18,2) NOT NULL CHECK (total > 0),
    currency VARCHAR(3) NOT NULL CHECK (currency = 'KZT'),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_order_user_key UNIQUE(user_id, idempotency_key)
);
CREATE INDEX idx_orders_user_created ON shop_orders(user_id, created_at, id);
CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES shop_orders(id),
    product_id BIGINT NOT NULL REFERENCES products(id),
    sku VARCHAR(40) NOT NULL,
    product_name VARCHAR(120) NOT NULL,
    unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price > 0),
    quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 99),
    CONSTRAINT uq_order_product UNIQUE(order_id, product_id)
);
